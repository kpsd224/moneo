const assert=require('node:assert/strict');
const ledger=require('../test-build/ledger.js');
const f=require('../test-build/finance.js');
const {DEMO_BOOK}=require('./legacySampleFixture.cjs');
let b=structuredClone(DEMO_BOOK);
const before=structuredClone(b);
const original=b.entries.find(e=>e.id==='demo-1');
b=ledger.upsertEntry(b,{...original,amount:900000,accountId:'cash',date:'2025-02-03',note:'Perbaikan sewa'},original.id);
assert.equal(b.entries.length,before.entries.length);
assert.equal(b.entries.find(e=>e.id===original.id).id,original.id);
assert.equal(f.accountBalance(b,'bni'),5300000);
assert.equal(f.accountBalance(b,'cash'),-600000);
assert.equal(f.periodSummary(b,'2025-01').expense,0);
assert.equal(f.periodSummary(b,'2025-02').expense,900000);
assert.equal(before.entries[0].amount,1600000,'Immutable update');
const count=b.entries.length;
b=ledger.upsertEntry(b,{date:'2025-02-10',kind:'saving',categoryId:'emergency',accountId:'bni',amount:200000,note:''});
assert.equal(b.entries.length,count+1);
assert.throws(()=>ledger.upsertEntry(b,{date:'2025-02-31',kind:'income',categoryId:'salary',accountId:'bni',amount:20,note:''}),/Tanggal/);
assert.throws(()=>ledger.upsertEntry(b,{date:'2025-02-10',kind:'income',categoryId:'rent',accountId:'bni',amount:20,note:''}),/Kategori/);
assert.throws(()=>ledger.upsertEntry(b,{date:'2025-02-10',kind:'income',categoryId:'salary',accountId:'missing',amount:20,note:''}),/Dompet/);
assert.throws(()=>ledger.upsertEntry(b,{date:'2025-02-10',kind:'income',categoryId:'salary',accountId:'bni',amount:20,note:''},'no-such-id'),/tidak ditemukan/);
const backup=ledger.backupJson(b,'2025-02','2026-11-17T00:00:00.000Z');
const restored=ledger.parseBackup(backup,f.safeBook);
assert.deepEqual(restored.book,b);
assert.equal(restored.period,'2025-02');
assert.throws(()=>ledger.parseBackup('{"app":"ana-budget","backupVersion":1}',f.safeBook),/Backup/);
let bad=JSON.parse(backup);bad.book.entries[0].categoryId='rent';
assert.throws(()=>ledger.parseBackup(JSON.stringify(bad),f.safeBook),/Backup/);
console.log('PASS: transaction edit preserves ID and balances; backup roundtrip rejects corrupted data');
