// rollover only previous unspent budget; positive surplus carries max 12 historic months
const budgetBook={...freshDemo(), entries:[],budgets:{'2025-01|rent':500000,'2025-02|rent':300000}};
assert.equal(Adv.plannedBudget(budgetBook,'2025-02','rent'),300000);
const roll=Adv.setOptions(budgetBook,{rollover:true,alertPercent:80});
