const assert=require('node:assert/strict');
const Adv=require('../src/advanced.js');
const {freshDemo}=require('./legacySampleFixture.cjs');
const F=require('../test-build/finance.js');
const {deleteAccount,deleteCategory}=require('../test-build/manage.js');
const {upsertEntry,backupJson,parseBackup}=require('../test-build/ledger.js');
let base=freshDemo();
const balance=id=>F.accountBalance(base,id);
const originalTotal=F.allBalances(base), originalPeriod=F.periodSummary(base,'2025-01');
base=Adv.addTransfer(base,{from:'bni',to:'cash',date:'2025-01-04',amount:100000,note:'Transfer internal'});
assert.equal(F.accountBalance(base,'bni'),3700000-100000); // demo: 5.3m less 1.6m rent
assert.equal(F.allBalances(base),originalTotal);
assert.deepEqual(F.periodSummary(base,'2025-01'),originalPeriod);
assert.ok(F.safeBook(base));
assert.throws(()=>deleteAccount(base,'bni'),/Keuangan\+/);
base=Adv.deleteTransfer(base,base.advanced.transfers[0].id);
assert.equal(F.allBalances(base),originalTotal);
base=Adv.addDebt(base,{name:'Pinjaman teman',type:'payable',accountId:'cash',date:'2025-01-04',principal:500000});
assert.equal(F.allBalances(base),originalTotal+500000);
assert.equal(Adv.netWorth(base),originalTotal);
let debtId=base.advanced.debts[0].id;
base=Adv.payDebt(base,{debtId,accountId:'cash',date:'2025-01-06',amount:200000});
assert.equal(F.allBalances(base),originalTotal+300000);
assert.equal(Adv.debtRemaining(base,debtId),300000);
assert.equal(Adv.netWorth(base),originalTotal);
assert.throws(()=>Adv.deleteDebt(base,debtId),/pelunasan/i);
base=Adv.saveGoal(base,{name:'Dana pendidikan',target:2000000,deadline:'2027-01-01'});
let goalId=base.advanced.goals[0].id;
const beforeAlloc=F.allBalances(base);
base=Adv.allocate(base,{goalId,accountId:'bni',date:'2025-01-07',amount:300000});
assert.equal(Adv.goalBalance(base,goalId),300000);
assert.equal(F.allBalances(base),beforeAlloc);
assert.throws(()=>Adv.allocate(base,{goalId,accountId:'cash',date:'2025-01-07',amount:-200000}),/tidak mencukupi/);
base=Adv.allocate(base,{goalId,accountId:'bni',date:'2025-01-08',amount:-200000});
assert.equal(Adv.goalBalance(base,goalId),100000);
base=Adv.addRecurring(base,{name:'Sewa tahunan',kind:'expense',categoryId:'rent',accountId:'bni',amount:100000,startDate:'2025-01-31'});
assert.equal(Adv.scheduled(base,'2025-02-28').length,1);
const once=Adv.postDue(base,'2025-02-28');
assert.equal(Adv.postDue(once,'2025-02-28').entries.length,once.entries.length);
assert.equal(once.entries[0].date,'2025-02-28');
assert.throws(()=>deleteCategory(once,'rent'),/Kategori/);
base=Adv.reconcile(once,{accountId:'bni',date:'2025-02-28',actual:100000});
assert.equal(F.accountBalance(base,'bni'),100000);
assert.ok(F.safeBook(base));
let corrupted=structuredClone(base);corrupted.advanced.transfers=[{id:'t',from:'xx',to:'yy',amount:20,date:'2025-01-01',note:''}];
assert.equal(F.safeBook(corrupted),false);
// rollover only previous unspent budget; positive surplus carries max 12 historic months
const budgetBook={...freshDemo(), entries:[],budgets:{'2025-01|rent':500000,'2025-02|rent':300000}};
assert.equal(Adv.plannedBudget(budgetBook,'2025-02','rent'),300000);
const roll=Adv.setOptions(budgetBook,{rollover:true,alertPercent:80});
assert.equal(Adv.plannedBudget(roll,'2025-02','rent'),800000);
assert.equal(Adv.plannedBudget(roll,'2025-03','rent'),800000);
let scheduledBook=freshDemo();
const balanceBeforeSchedule=F.allBalances(scheduledBook);
scheduledBook=Adv.saveScheduledPayment(scheduledBook,{name:'Internet',accountId:'bni',categoryId:'rent',amount:175000,dueDate:'2025-02-17'});
const scheduledId=scheduledBook.advanced.scheduledPayments[0].id;
assert.equal(F.allBalances(scheduledBook),balanceBeforeSchedule);
assert.equal(Adv.paymentOutlook(scheduledBook,'2025-02-01',30).totalDue,175000);
assert.equal(Adv.paymentOutlook(scheduledBook,'2025-02-17',30).dueTodayCount,1);
assert.equal(Adv.paymentOutlook(scheduledBook,'2025-02-18',30).overdueCount,1);
assert.equal(Adv.paymentOutlook(scheduledBook,'2025-01-01',30).pending.length,0);
assert.throws(()=>Adv.paymentOutlook(scheduledBook,'2025-02-30',30),/Rentang/);
assert.equal(Adv.forecast(scheduledBook,'2025-02').pending.some(p=>p.id===scheduledId),true);
assert.ok(F.safeBook(scheduledBook));
assert.throws(()=>deleteAccount(scheduledBook,'bni'),/Keuangan\+/);
assert.throws(()=>deleteCategory(scheduledBook,'rent'),/Kategori/);
assert.throws(()=>Adv.saveScheduledPayment(scheduledBook,{name:'Salah',accountId:'bni',categoryId:'rent',amount:100,dueDate:'2025-02-30'}),/tanggal/);
scheduledBook=Adv.saveScheduledPayment(scheduledBook,{name:'Internet rumah',accountId:'bni',categoryId:'rent',amount:180000,dueDate:'2025-02-18'},scheduledId);
assert.equal(scheduledBook.advanced.scheduledPayments.length,1);
const posted=upsertEntry(scheduledBook,{date:'2025-02-18',kind:'expense',categoryId:'rent',accountId:'bni',amount:180000,note:'Internet rumah'});
scheduledBook=Adv.markScheduledPaymentPaid(posted,scheduledId,posted.entries[0].id);
assert.equal(F.allBalances(scheduledBook),balanceBeforeSchedule-180000);
assert.equal(Adv.paymentOutlook(scheduledBook,'2025-02-01',30).totalDue,0);
assert.equal(Adv.forecast(scheduledBook,'2025-02').pending.some(p=>p.id===scheduledId),false);
assert.equal(parseBackup(backupJson(scheduledBook,'2025-02'),F.safeBook).book.advanced.scheduledPayments[0].paidEntryId,posted.entries[0].id);
assert.throws(()=>Adv.markScheduledPaymentPaid(scheduledBook,scheduledId,posted.entries[0].id),/sudah dibayar/);
assert.throws(()=>Adv.saveScheduledPayment(scheduledBook,{name:'Edit lagi',accountId:'bni',categoryId:'rent',amount:180000,dueDate:'2025-02-18'},scheduledId),/sudah dibayar/);
assert.ok(F.safeBook(scheduledBook));
const brokenLink=structuredClone(scheduledBook);brokenLink.advanced.scheduledPayments[0].paidEntryId='missing-entry';
assert.equal(F.safeBook(brokenLink),false);
scheduledBook=Adv.unlinkScheduledEntry({...scheduledBook,entries:scheduledBook.entries.filter(e=>e.id!==posted.entries[0].id)},posted.entries[0].id);
assert.equal(scheduledBook.advanced.scheduledPayments[0].paidEntryId,'');
assert.equal(F.allBalances(scheduledBook),balanceBeforeSchedule);
assert.ok(F.safeBook(scheduledBook));
scheduledBook=Adv.deleteScheduledPayment(scheduledBook,scheduledId);
assert.equal(scheduledBook.advanced.scheduledPayments.length,0);
const legacyAdvanced=structuredClone(scheduledBook);delete legacyAdvanced.advanced.scheduledPayments;
assert.ok(F.safeBook(legacyAdvanced));
let shortfallBook=freshDemo();
shortfallBook=Adv.saveScheduledPayment(shortfallBook,{name:'Tagihan besar',accountId:'bni',categoryId:'rent',amount:F.accountBalance(shortfallBook,'bni')+250000,dueDate:'2025-02-20'});
assert.equal(Adv.paymentOutlook(shortfallBook,'2025-02-01',30).accountShortfalls[0].shortfall,250000);
assert.equal(F.accountBalance(shortfallBook,'bni'),F.accountBalance(freshDemo(),'bni'));
let splitBook=freshDemo();
const originalAssets=F.allBalances(splitBook);
splitBook=Adv.saveGoal(splitBook,{name:'Dana sekolah',target:500000,deadline:''});
splitBook=Adv.allocate(splitBook,{goalId:splitBook.advanced.goals[0].id,accountId:'bni',date:'2025-01-12',amount:200000});
assert.deepEqual(Adv.savingsPosition(splitBook),{available:originalAssets-200000,reserved:200000,portfolio:0,savings:200000,assets:originalAssets});
splitBook=upsertEntry(splitBook,{date:'2025-01-13',kind:'saving',categoryId:'emergency',accountId:'bni',amount:100000,note:'Dana darurat'});
assert.equal(F.allBalances(splitBook),originalAssets-100000);
assert.deepEqual(Adv.savingsPosition(splitBook),{available:originalAssets-300000,reserved:200000,portfolio:100000,savings:300000,assets:originalAssets});
assert.equal(Adv.netWorth(splitBook),originalAssets);
assert.equal(Adv.forecast(splitBook,'2025-03').projected,originalAssets-300000);
splitBook=Adv.withdrawSavings(splitBook,{categoryId:'emergency',accountId:'cash',amount:40000,date:'2025-01-14'});
assert.equal(Adv.savingCategoryBalance(splitBook,'emergency'),60000);
assert.equal(F.allBalances(splitBook),originalAssets-60000);
assert.equal(Adv.savingsPosition(splitBook).assets,originalAssets);
assert.throws(()=>Adv.withdrawSavings(splitBook,{categoryId:'emergency',accountId:'cash',amount:70000,date:'2025-01-15'}),/tidak cukup/);
assert.ok(F.safeBook(splitBook));
assert.equal(F.safeBook({...splitBook,entries:splitBook.entries.filter(e=>e.kind!=='saving')}),false);
splitBook=Adv.deleteSavingsWithdrawal(splitBook,splitBook.advanced.savingsWithdrawals[0].id);
assert.equal(Adv.savingsPortfolio(splitBook),100000);
const oldSavings=structuredClone(splitBook);delete oldSavings.advanced.savingsWithdrawals;
assert.ok(F.safeBook(oldSavings));
console.log('PASS: transfer, debts, goals, recurring, scheduled payments, reconciliation, rollover, strict validation');
