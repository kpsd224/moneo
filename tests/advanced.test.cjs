const assert=require('node:assert/strict');
const Adv=require('../src/advanced.js');
const {freshDemo}=require('./legacySampleFixture.cjs');
const F=require('../test-build/finance.js');
const {deleteAccount,deleteCategory}=require('../test-build/manage.js');
let base=freshDemo();
const balance=id=>F.accountBalance(base,id);
const originalTotal=F.allBalances(base), originalPeriod=F.periodSummary(base,'2025-01');
base=Adv.addTransfer(base,{from:'bni',to:'cash',date:'2025-01-04',amount:100000,note:'Transfer internal'});
assert.equal(F.accountBalance(base,'bni'),3700000-100000); // demo: 5.3m less 1.6m rent
assert.equal(F.allBalances(base),originalTotal);
assert.deepEqual(F.periodSummary(base,'2025-01'),originalPeriod);
assert.ok(F.safeBook(base));
assert.throws(()=>deleteAccount(base,'bni'),/Keuangan\+/);
base=Adv.deleteTransfer(base,base.advanced.transfers[0].id);
assert.equal(F.allBalances(base),originalTotal);
base=Adv.addDebt(base,{name:'Pinjaman teman',type:'payable',accountId:'cash',date:'2025-01-04',principal:500000});
assert.equal(F.allBalances(base),originalTotal+500000);
assert.equal(Adv.netWorth(base),originalTotal);
let debtId=base.advanced.debts[0].id;
base=Adv.payDebt(base,{debtId,accountId:'cash',date:'2025-01-06',amount:200000});
assert.equal(F.allBalances(base),originalTotal+300000);
assert.equal(Adv.debtRemaining(base,debtId),300000);
assert.equal(Adv.netWorth(base),originalTotal);
assert.throws(()=>Adv.deleteDebt(base,debtId),/pelunasan/i);
base=Adv.saveGoal(base,{name:'Dana pendidikan',target:2000000,deadline:'2027-01-01'});
let goalId=base.advanced.goals[0].id;
const beforeAlloc=F.allBalances(base);
base=Adv.allocate(base,{goalId,accountId:'bni',date:'2025-01-07',amount:300000});
assert.equal(Adv.goalBalance(base,goalId),300000);
assert.equal(F.allBalances(base),beforeAlloc);
assert.throws(()=>Adv.allocate(base,{goalId,accountId:'cash',date:'2025-01-07',amount:-200000}),/tidak mencukupi/);
base=Adv.allocate(base,{goalId,accountId:'bni',date:'2025-01-08',amount:-200000});
assert.equal(Adv.goalBalance(base,goalId),100000);
base=Adv.addRecurring(base,{name:'Sewa tahunan',kind:'expense',categoryId:'rent',accountId:'bni',amount:100000,startDate:'2025-01-31'});
assert.equal(Adv.scheduled(base,'2025-02-28').length,1);
const once=Adv.postDue(base,'2025-02-28');
assert.equal(Adv.postDue(once,'2025-02-28').entries.length,once.entries.length);
assert.equal(once.entries[0].date,'2025-02-28');
assert.throws(()=>deleteCategory(once,'rent'),/Kategori/);
base=Adv.reconcile(once,{accountId:'bni',date:'2025-02-28',actual:100000});
assert.equal(F.accountBalance(base,'bni'),100000);
assert.ok(F.safeBook(base));
